#!/usr/bin/env node
'use strict';
/* =====================================================================
   D|R Painting static site build. Plain Node, no dependencies.
     node src/build.js
   Deletes site/ and regenerates every page from src/config.js and
   src/templates/, copies src/assets/ and writes assets/config.js,
   sitemap.xml and robots.txt.
   ===================================================================== */
const fs = require('fs');
const path = require('path');

const SRC = __dirname;
const OUT = path.join(SRC, '..', 'site');
const C = require('./config.js');
const { layout } = require('./templates/layout');
const H = require('./templates/helpers');

/* ---------- Sanity checks on config ---------- */
const ids = new Set(C.services.map((s) => s.id));
const problems = [];
C.services.forEach((s) => {
  ['slug', 'metaTitle', 'metaDescription', 'intro', 'headline'].forEach((k) => { if (!s[k]) problems.push(`services.${s.id}: missing ${k}`); });
  ['included', 'steps', 'faqs', 'related'].forEach((k) => { if (!Array.isArray(s[k]) || !s[k].length) problems.push(`services.${s.id}: ${k} must be a non-empty array`); });
  (s.related || []).forEach((r) => { if (!ids.has(r)) problems.push(`services.${s.id}: related id "${r}" does not exist`); });
  if (!C.IMG[s.img]) problems.push(`services.${s.id}: IMG.${s.img} missing`);
});
if (!/\/$/.test(C.business.url)) problems.push('business.url must end with a slash');
if (problems.length) { console.error('Config problems:\n  ' + problems.join('\n  ')); process.exit(1); }

/* ---------- Pages ---------- */
const P = (name) => require('./templates/pages/' + name)(C);
const pages = [].concat(P('home'), P('services'), P('service'), P('our-work'), P('about'), P('areas'), P('contact'), P('404'));
const files = pages.map((p) => p.file);
if (new Set(files).size !== files.length) { console.error('Duplicate output file names: ' + files.join(', ')); process.exit(1); }

/* ---------- Write ---------- */
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'assets'), { recursive: true });

for (const f of fs.readdirSync(path.join(SRC, 'assets'))) {
  fs.copyFileSync(path.join(SRC, 'assets', f), path.join(OUT, 'assets', f));
}
fs.writeFileSync(path.join(OUT, 'assets', 'config.js'),
  '/* Generated by src/build.js from src/config.js. Edit that file and rebuild; changes made here are lost on the next build. */\n'
  + 'window.CONFIG = ' + JSON.stringify(C, null, 2) + ';\n');

for (const p of pages) fs.writeFileSync(path.join(OUT, p.file), layout(C, p));

const today = new Date().toISOString().slice(0, 10);
const indexable = pages.filter((p) => !p.noindex);
fs.writeFileSync(path.join(OUT, 'sitemap.xml'),
  '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
  + indexable.map((p) => `  <url><loc>${H.esc(H.absUrl(C, p.file))}</loc><lastmod>${today}</lastmod></url>`).join('\n')
  + '\n</urlset>\n');
fs.writeFileSync(path.join(OUT, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${C.business.url}sitemap.xml\n`);

const kb = (f) => (fs.statSync(path.join(OUT, f)).size / 1024).toFixed(1) + ' KB';
console.log(`Built ${pages.length} pages into ${path.relative(process.cwd(), OUT) || OUT}/`);
pages.forEach((p) => console.log(`  ${p.file.padEnd(36)} ${kb(p.file)}`));
fs.readdirSync(path.join(OUT, 'assets')).forEach((f) => console.log(`  assets/${f.padEnd(29)} ${kb('assets/' + f)}`));
console.log(`  sitemap.xml (${indexable.length} URLs), robots.txt`);
