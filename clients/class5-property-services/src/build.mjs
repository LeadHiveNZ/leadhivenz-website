#!/usr/bin/env node
// Class 5 Property Services - static site builder. Node 22, zero dependencies.
//   node src/build.mjs            rebuild site/ (everything except site/images/)
//   node src/build.mjs --assets   also regenerate resized photos, favicons and OG image (needs ImageMagick)
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, copyFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { site } from './data/site.mjs';
import { services } from './data/services.mjs';
import { suburbs } from './data/suburbs.mjs';
import { testimonials } from './data/testimonials.mjs';
import { head } from './partials/head.mjs';
import { header } from './partials/header.mjs';
import { footer } from './partials/footer.mjs';
import { ctaBand } from './partials/cta-band.mjs';
import { stickyBar } from './partials/sticky-bar.mjs';
import { home } from './pages/home.mjs';
import { servicesHub } from './pages/services-hub.mjs';
import { servicePage } from './pages/service.mjs';
import { areasHub, suburbPage } from './pages/areas.mjs';
import { about } from './pages/about.mjs';
import { ourWork } from './pages/our-work.mjs';
import { contact } from './pages/contact.mjs';
import { thankYou, notFound } from './pages/misc.mjs';

const SRC = dirname(fileURLToPath(import.meta.url));
const ROOT = join(SRC, '..');
const OUT = join(ROOT, 'site');

if (process.argv.includes('--assets')) {
  const { makeAssets } = await import('./assets.mjs');
  makeAssets(ROOT);
  console.log('✓ regenerated images, favicons and OG image');
}

// 1. Clean site/ except images/
mkdirSync(OUT, { recursive: true });
for (const entry of readdirSync(OUT)) if (entry !== 'images') rmSync(join(OUT, entry), { recursive: true, force: true });

const write = (rel, content) => {
  const file = join(OUT, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
};
const hash = (s) => createHash('sha1').update(s).digest('hex').slice(0, 8);

// 2. CSS + JS (light minification: comments and whitespace only)
const css = readFileSync(join(SRC, 'assets', 'style.css'), 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/\s+/g, ' ')
  .replace(/\s*([{}:;,>])\s*/g, '$1')
  .replace(/;}/g, '}')
  .trim();
const js = readFileSync(join(SRC, 'assets', 'main.js'), 'utf8')
  .split('\n')
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith('//'))
  .join('\n');
write('css/style.css', css);
write('js/main.js', js);
const assetV = { css: hash(css), js: hash(js) };

// 3. Pages
const pages = [
  home(),
  servicesHub(),
  ...services.map(servicePage),
  areasHub(),
  ...suburbs.map(suburbPage),
  about(),
  ourWork(),
  contact(),
  thankYou(),
  notFound(),
];

const layout = (p) => `<!doctype html>
<html lang="en-NZ">
${head({ ...p, assetV })}
<body>
${header(p.path)}
<main id="main" tabindex="-1">
${p.body}
</main>
${p.noCta ? '' : ctaBand()}
${footer()}
${stickyBar()}
</body>
</html>
`;

const words = (html) => html.replace(/<script[\s\S]*?<\/script>/g, ' ').replace(/<[^>]+>/g, ' ').replace(/&[a-z#0-9]+;/g, ' ').split(/\s+/).filter((w) => /[a-z0-9]/i.test(w)).length;
const report = [];
for (const p of pages) {
  const file = p.path.endsWith('.html') ? p.path.slice(1) : `${p.path.slice(1)}index.html`;
  write(file, layout(p));
  if (p.wordScope) report.push(`${p.path}  ${words(p.body.replace(/<!--wc:skip-->[\s\S]*?<!--\/wc:skip-->/g, ''))} words of page copy (excl. related-services cards)`);
  if (p.suburbWords) report.push(`${p.path}  ${words(p.suburbWords)} words of unique intro`);
  if (p.title.length > 60) console.warn(`! title over 60 chars (${p.title.length}): ${p.path}`);
  if (p.desc.length > 155) console.warn(`! description over 155 chars (${p.desc.length}): ${p.path}`);
}

// 4. Static files: favicons, OG image (generated by --assets into src/static)
for (const f of readdirSync(join(SRC, 'static'))) copyFileSync(join(SRC, 'static', f), join(OUT, f));

// 5. sitemap.xml, robots.txt, webmanifest, netlify.toml
const today = new Date().toISOString().slice(0, 10);
const indexable = pages.filter((p) => !p.noindex);
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${indexable.map((p) => `  <url><loc>${site.url}${p.path}</loc><lastmod>${today}</lastmod><priority>${p.path === '/' ? '1.0' : p.path.split('/').length > 3 ? '0.7' : '0.8'}</priority></url>`).join('\n')}
</urlset>
`);
write('robots.txt', `User-agent: *
Allow: /
Disallow: /thank-you/

Sitemap: ${site.url}/sitemap.xml
`);
write('site.webmanifest', JSON.stringify({
  name: site.name,
  short_name: 'Class 5',
  description: site.description,
  start_url: '/',
  display: 'standalone',
  background_color: '#0B0B0D',
  theme_color: '#0B0B0D',
  icons: [
    { src: '/icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: '/favicon.png', sizes: '512x512', type: 'image/png' },
  ],
}, null, 2) + '\n');
write('netlify.toml', `# Netlify config. This folder is the deploy: drag the zipped site/ folder onto Netlify.
[build]
  publish = "."

[[headers]]
  for = "/*"
  [headers.values]
    X-Frame-Options = "DENY"
    X-Content-Type-Options = "nosniff"
    Referrer-Policy = "strict-origin-when-cross-origin"
    Permissions-Policy = "camera=(), microphone=(), geolocation=()"

[[headers]]
  for = "/images/*"
  [headers.values]
    Cache-Control = "public, max-age=2592000"

[[headers]]
  for = "/css/*"
  [headers.values]
    Cache-Control = "public, max-age=31536000, immutable"

[[headers]]
  for = "/js/*"
  [headers.values]
    Cache-Control = "public, max-age=31536000, immutable"

[[redirects]]
  from = "/index.html"
  to = "/"
  status = 301
  force = true

[[redirects]]
  from = "/*/index.html"
  to = "/:splat/"
  status = 301
  force = true

[[redirects]]
  from = "/*"
  to = "/404.html"
  status = 404
`);

console.log(`✓ built ${pages.length} pages → ${OUT}`);
console.log(`  css ${(css.length / 1024).toFixed(1)} KB · js ${(js.length / 1024).toFixed(1)} KB`);
report.forEach((r) => console.log('  ' + r));
if (testimonials.some((t) => t.placeholder)) console.warn('! testimonials are still PLACEHOLDERS - replace in src/data/testimonials.mjs before launch');
