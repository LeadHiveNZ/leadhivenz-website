CREATE TABLE public.tradie_signups (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  full_name text NOT NULL,
  business_name text,
  phone text NOT NULL,
  email text NOT NULL,
  nzbn text,
  gst_registered boolean NOT NULL DEFAULT false,
  gst_number text,
  trades text[] NOT NULL,
  towns text NOT NULL,
  work_days text[] NOT NULL DEFAULT '{}',
  licences jsonb NOT NULL DEFAULT '[]'::jsonb,
  lbp_number text,
  insurer text NOT NULL,
  policy_number text NOT NULL,
  insurance_expiry date NOT NULL,
  insurance_file_path text NOT NULL,
  record_file_path text,
  record_requested boolean NOT NULL DEFAULT false,
  existing_clients text,
  agreement_version text NOT NULL DEFAULT '21 November 2026',
  agreement_sha256 text NOT NULL,
  signature_name text NOT NULL,
  signed_at timestamptz NOT NULL DEFAULT now(),
  signer_ip text,
  signer_user_agent text,
  utm_source text,
  utm_campaign text,
  utm_content text
);
GRANT ALL ON public.tradie_signups TO service_role;
ALTER TABLE public.tradie_signups ENABLE ROW LEVEL SECURITY;
